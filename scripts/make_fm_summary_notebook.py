def build_markdown():
    """docs/fm_encoder_summary.md from the executed notebook."""
    nb = nbf.read(NB, as_version=4)
    if not any(c.get("outputs") for c in nb.cells if c.cell_type == "code"):
        raise SystemExit(f"{NB} is not executed")
    parts = []
    for c in nb.cells:
        tags = c.metadata.get("tags", [])
        if c.cell_type == "markdown":
            if "md-skip" in tags:
                continue
            text = c.source.replace(
                "📄 **[PDF version](fm_encoder_summary.pdf)** (figures, tables and formulas, no code)",
                "Generated from the notebook [`notebooks/fm_encoder_summary.ipynb`](../notebooks/fm_encoder_summary.ipynb) "
                "(**[PDF version](../notebooks/fm_encoder_summary.pdf)**) by `scripts/make_fm_summary_notebook.py "
                "--markdown`; edit the generator, not this file.")
            parts.append(text)
            continue
        for t in tags:
            if t.startswith("md-table:"):
                number = t.split(":", 1)[1]
                with open(os.path.join(TABLES, f"table_{number.replace('.', '_')}.md")) as fh:
                    parts.append(fh.read().strip())
            elif t.startswith("md-figure:"):
                name = t.split(":", 1)[1]
                heading = next((re.search(r"### (Figure \d+\.\d+)", p) for p in reversed(parts)
                                if re.search(r"### Figure \d+\.\d+", p)), None)
                label = heading.group(1) if heading else "Figure"
                parts.append(f"![{label}](figures/fm_encoders/{name})")
    with open(DOC, "w") as fh:
        fh.write("\n\n".join(parts) + "\n")
    print("wrote", DOC)


